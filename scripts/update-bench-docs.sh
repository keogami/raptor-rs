#!/usr/bin/env bash
set -euo pipefail

echo "Running benchmarks..."
output=$(cargo bench -- --output-format bencher 2>/dev/null)

cat > BENCHMARKS.md << 'HEADER'
# Benchmark Results

> Auto-generated by `scripts/update-bench-docs.sh`

| Benchmark | Time (ns/iter) | Variance (+/- ns) |
|-----------|---------------:|---------:|
HEADER

echo "$output" | grep "^test " | while read -r line; do
    name=$(echo "$line" | awk '{print $2}')
    time=$(echo "$line" | awk '{print $5}')
    variance=$(echo "$line" | awk '{print $7}')
    echo "| \`${name}\` | ${time} | ${variance} |" >> BENCHMARKS.md
done

echo ""
echo "Results written to BENCHMARKS.md"
